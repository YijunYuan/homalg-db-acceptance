"""Generate Horizon's leanblueprint input from authored node headers."""

import re
from pathlib import Path
from typing import Any

from homalg.documents import dump_metadata, read_document
from homalg.engine import active_documents
from homalg.headers import parse_header
from homalg.io import atomic_write
from homalg.repository import documents, node_paths
from homalg.schemas import load_yaml

GENERATED = "% GENERATED by homalg blueprint-tex; do not edit.\n"
ENVIRONMENTS = {"construction": "definition", "axiom": "definition", "exercise": "example"}


def natural(value: str) -> tuple[tuple[int, str | int], ...]:
    """Sort source labels naturally while retaining deterministic text ordering."""
    return tuple(
        (0, int(part)) if part.isdigit() else (1, part.lower())
        for part in re.split(r"([0-9]+)", value)
        if part
    )


def source_order(repo: Path, key: str, headers: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Use the page inventory's occurrence order when available, otherwise source coordinates."""
    path = repo / "literature" / key / "inventory.yaml"
    rank: dict[str, int] = {}
    if path.exists():
        inventory = load_yaml(path.read_text())
        for _, page in sorted(inventory.get("pages", {}).items()):
            if isinstance(page, dict):
                for item in page.get("items", []):
                    if isinstance(item.get("node"), str):
                        rank.setdefault(item["node"], len(rank))

    def order(item: dict[str, Any]) -> tuple[Any, ...]:
        source = item["source"]
        return (
            natural(source.get("chapter", "")),
            min(source["pages"]),
            rank.get(item["id"], len(rank)),
            natural(source.get("section", "")),
            natural(source["label"]),
            item["id"],
        )

    return sorted(headers, key=order)


def escape_text(text: str) -> str:
    """Escape prose characters while retaining mathematical fragments verbatim."""
    escaped = {
        "\\": r"\textbackslash{}",
        "#": r"\#",
        "%": r"\%",
        "&": r"\&",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(escaped.get(char, char) for char in text)


def markdown_tex(text: str) -> str:
    """Translate restrained prose markup without rewriting source mathematics."""
    pattern = (
        r"(\$\$[\s\S]*?\$\$|(?<!\\)\$[^\n]*?(?<!\\)\$|\\\[[\s\S]*?\\\]|\\\([\s\S]*?\\\)"
        r"|\[uses\s+`?[A-Za-z0-9_.]+`?\]|`[^`\n]+`)"
    )
    parts = re.split(pattern, text)
    for index in range(1, len(parts), 2):
        if parts[index].startswith("`"):
            parts[index] = r"\texttt{" + escape_text(parts[index][1:-1]) + "}"
        elif parts[index].startswith("[uses"):
            node_id = parts[index][5:-1].strip().strip("`")
            parts[index] = rf"\ref{{{node_id}}}"
    for index in range(0, len(parts), 2):
        value = escape_text(parts[index])
        value = re.sub(r"\*\*([^*\s](?:[^*]*[^*\s])?)\*\*", r"\\textbf{\1}", value)
        value = re.sub(r"(?<!\*)\*([^*\s](?:[^*]*[^*\s])?)\*(?!\*)", r"\\emph{\1}", value)
        parts[index] = value
    return "".join(parts)


def render_node(
    metadata: dict[str, Any],
    sections: dict[str, str],
    document: dict[str, Any],
    *,
    stub: bool = False,
) -> str:
    """Render one node, distinguishing statement locks from actual proof completion."""
    kind = ENVIRONMENTS.get(metadata["kind"], metadata["kind"])
    title = metadata.get("title") or metadata["source"]["label"]
    if "cited" in metadata:
        title += " (cited)"
    lines = [rf"\begin{{{kind}}}[{{{escape_text(title)}}}]", rf"\label{{{metadata['id']}}}"]
    mathlib = metadata.get("mathlib", {})
    declaration_names = metadata["decls"]
    if "aux" in metadata and mathlib.get("relation") == "same":
        lines.append(r"\mathlibok")
        declaration_names = mathlib.get("decls", [])
    if declaration_names:
        lines.append(r"\lean{" + ", ".join(declaration_names) + "}")
    if metadata["fidelity"].get("reviewed"):
        lines.append(r"\leanok")
    if not stub and metadata["deps"]["statement"]:
        lines.append(r"\uses{" + ", ".join(metadata["deps"]["statement"]) + "}")
    offset = document.get("pdf", {}).get("page_offset", 0)
    anchors = [f"{metadata['doc']}:page-{page + offset:04}" for page in metadata["source"]["pages"]]
    lines.append(r"\source{" + ", ".join(anchors) + "}")
    statement = sections.get("Statement", "")
    if stub:
        statement = re.split(r"(?<=[.!?])\s+", statement, maxsplit=1)[0]
    lines.extend((markdown_tex(statement), rf"\end{{{kind}}}"))
    if not stub and (sections.get("Proof") or metadata["deps"]["proof"]):
        lines.append(r"\begin{proof}")
        if metadata["deps"]["proof"]:
            lines.append(r"\uses{" + ", ".join(metadata["deps"]["proof"]) + "}")
        lines.extend((markdown_tex(sections.get("Proof", "")), r"\end{proof}"))
    return "\n".join(lines) + "\n"


def generate(repo: Path, selected: tuple[str, ...] = (), *, active: bool = False) -> dict[str, str]:
    """Build deterministic content and a narrowly scoped graph configuration."""
    if active and selected:
        raise ValueError("Choose --active or --doc, not both")
    keys = active_documents(repo) if active else documents(repo, selected)
    all_headers = {
        header.metadata["id"]: header
        for path in node_paths(repo, documents(repo))
        for header in [parse_header(path.read_text())]
    }
    included = {
        node_id for node_id, header in all_headers.items() if header.metadata["doc"] in keys
    }
    external = {
        dependency
        for node_id in included
        for dependency in sum(all_headers[node_id].metadata["deps"].values(), [])
        if dependency not in included and dependency in all_headers
    }
    external_keys = sorted({all_headers[node_id].metadata["doc"] for node_id in external})
    output = [GENERATED]
    for key in [*keys, *external_keys]:
        document = read_document(repo, key)
        stub = key not in keys
        metadata = [
            header.metadata
            for node_id, header in all_headers.items()
            if header.metadata["doc"] == key and (not stub or node_id in external)
        ]
        chapter = None
        for item in source_order(repo, key, metadata):
            new_chapter = item["source"].get("chapter", "")
            if chapter != new_chapter:
                title = f"External: {key}" if stub else f"{key} — Chapter {new_chapter}"
                output.append(r"\chapter{" + escape_text(title) + "}\n")
                chapter = new_chapter
            output.append(render_node(item, all_headers[item["id"]].sections, document, stub=stub))
    config = {
        "blueprint": "blueprint/src/content.tex",
        "lean": [f"HomAlg/{key}" for key in sorted(set(keys + external_keys))],
    }
    return {
        "blueprint/src/content.tex": "\n".join(output),
        "hgraph/config.yaml": "# GENERATED by homalg blueprint-tex; do not edit.\n"
        + dump_metadata(config),
    }


def write(repo: Path, selected: tuple[str, ...] = (), *, active: bool = False) -> list[str]:
    """Publish generated files atomically without touching comments or reviews in hgraph."""
    files = generate(repo, selected, active=active)
    for relative, text in files.items():
        atomic_write(repo / relative, text)
    return sorted(files)
